/**
 * Поиск диагноза по коду (без учёта регистра).
 * @param {string} code код МКБ-10
 * @returns {{code:string,name:string}|undefined}
 */
function findByCode(code) {
  const c = String(code || '').trim().toUpperCase();
  return MKB10.find((d) => d.code.toUpperCase() === c);
}

/**
 * Поиск диагнозов по тексту (частичное совпадение).
 * @param {string} query текст запроса
 * @param {number} limit максимальное число результатов
 * @returns {Array<{code:string,name:string}>}
 */
function search(query, limit = 10) {
  const q = String(query || '').trim().toLowerCase();
  if (!q) return [];
  const hits = MKB10.filter(
    (d) => d.code.toLowerCase().includes(q) || d.name.toLowerCase().includes(q),
  );
  return hits.slice(0, limit);
}

